export default function CoordenacaoShell({ children }) {
  const pathname = usePathname();
  const [menuOpen, setMenuOpen] = useState(false);
  const [coordenador, setCoordenador] = useState(null);

  useEffect(() => {
    fetch(`${API_BASE}/api/coordenacao/auth`, { credentials: "include" })
      .then((r) => r.json())
      .then((d) => { if (d.return) setCoordenador(d.coordenador || null); })
      .catch(() => {});
  }, []);

  function isActive(href) {
    if (href === "/coordenacao") return pathname === "/coordenacao";
    if (href === "/corrigir/turmas") return pathname.startsWith("/corrigir/turmas");
    return pathname === href || pathname.startsWith(href + "/");
  }

  return (
    <div className={styles.page}>
      <div className={styles.shell}>
        <aside className={`${styles.sidebar} ${menuOpen ? styles.sidebarOpen : ""}`}>
          <div className={styles.sidebarHeader}>
            <Image src={logo} alt="Logo do SIAA" className={styles.sidebarLogo} priority />
            <span className={styles.sidebarBrand}>SIAA</span>
          </div>

          <nav className={styles.nav}>
            {NAV_ITEMS.map((item) => (
              <Link
                key={item.href}
                href={item.href}
                className={isActive(item.href) ? styles.navLinkActive : styles.navLink}
                onClick={() => setMenuOpen(false)}
              >
                {item.icon}
                {item.label}
              </Link>
            ))}
          </nav>

          <div className={styles.sidebarFooter}>
            <span className={styles.coordName}>{coordenador?.nome_completo || "Coordenador"}</span>
            <span className={styles.coordEscola}>{coordenador?.escola || ""}</span>
          </div>
        </aside>

        {menuOpen && (
          <button className={styles.overlay} aria-label="Fechar menu" onClick={() => setMenuOpen(false)} />
        )}

        <div className={styles.content}>
          <header className={styles.topbar}>
            <button className={styles.menuButton} aria-label="Abrir menu" onClick={() => setMenuOpen(true)}>
              <svg width="22" height="22" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round">
                <line x1="4" y1="6" x2="20" y2="6" />
                <line x1="4" y1="12" x2="20" y2="12" />
                <line x1="4" y1="18" x2="20" y2="18" />
              </svg>
            </button>
            <span className={styles.topbarTitle}>Painel da Organização</span>
          </header>
          {children}
        </div>
      </div>
    </div>
  );
}
